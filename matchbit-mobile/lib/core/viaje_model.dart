class Viaje {
  final String destino;
  final String unidad;
  final String pago;
  final String precio;
  final String codigo;
  final String fecha;
  final String hora;
  final String tipo;
  final String estado;

  Viaje({
    required this.destino,
    required this.unidad,
    required this.pago,
    required this.precio,
    required this.codigo,
    required this.fecha,
    required this.hora,
    required this.tipo,
    required this.estado,
  });
}